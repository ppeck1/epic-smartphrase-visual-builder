// ---------- block rendering ----------
  const KIND_LABEL = {"free-text": "Text", wildcard: "Wildcard", smartlink: "SmartLink", "catalog-smartlink": "SmartLink to insert", "existing-smartlist": "SmartList", "catalog-smartlist": "SmartList to insert", "custom-smartlist": "SmartList plan", template: "Template"};
  const kindLabel = (node) => node.moduleId === "personal-placeholder" ? "Placeholder" : node.moduleId === "nested-smartphrase" ? "Nested phrase" : (KIND_LABEL[node.kind] || node.kind);
  const isCollapsible = (node) => ["free-text", "template", "custom-smartlist"].includes(node.kind);
  const textIsLong = (t) => (String(t || "").split("\n").length > 3 || String(t || "").length > 240);

  const JOINABLE = ["free-text", "wildcard", "smartlink", "existing-smartlist", "catalog-smartlink", "catalog-smartlist"];
  function canJoin(i) { return i > 0 && nodes[i - 1] && nodes[i - 1].kind === "free-text" && JOINABLE.includes(nodes[i].kind) && nodeOutput(nodes[i]) !== ""; }
  function blockSig(node, i, count) {
    return [canJoin(i) ? "j" : "", node.kind, node.evidence, node.label, node.token, node.collapsed ? "c" : "o", i, count, node.collapsed ? (node.text + node.listName + node.choices + node.multiple) : ""].join("␟");
  }
  function flagHtml(node) {
    if (node.kind === "wildcard") return `<span class="flag later">Fill in when documenting</span>`;
    if (node.evidence === "observed") return `<span class="flag check" title="${esc(EVIDENCE.observed.note)}">${icon("alert", 15)}Check in Epic</span>`;
    if (node.evidence === "catalog" || node.evidence === "creation") return `<span class="flag check" title="${esc(EVIDENCE[node.evidence].note)}">${icon("alert", 15)}Set up in Epic</span>`;
    return "";
  }
  function tokenClass(token) {
    if (token === "***") return "tok-wild";
    if (PLACEHOLDER_INSERT.test(token) || PLACEHOLDER_PERSONAL.test(token) || PLACEHOLDER_ADD.test(token)) return "tok-plan";
    return "tok-link";
  }
  function blockContent(node, i) {
    // Imported IDs are regenerated by core validation; escaping here adds a second boundary.
    const id = esc(`f-${node.uid}`);
    if (node.kind === "free-text" || node.kind === "template") {
      const caption = node.kind === "template" ? `<p class="caption">${icon("library", 15)}Template · ${esc(node.label)}<span style="margin-left:auto">${flagHtml(node)}</span></p>` : "";
      if (node.collapsed) {
        const lines = String(node.text || "").split("\n");
        const first = lines.find((l) => l.trim()) || "(empty)";
        return `${caption}<button type="button" class="summary-btn" data-act="expand" aria-label="Expand block ${i + 1}"><span class="sum-text">${esc(first)}</span><span class="sum-meta">${lines.length > 1 ? `+${plural(lines.length - 1, "line")} · ` : ""}Expand</span></button>`;
      }
      return `${caption}<label class="sr-only" for="${id}-text">Block ${i + 1} text</label><div class="ink"><div class="ink-back" aria-hidden="true"></div><textarea class="doc-text" id="${id}-text" data-field="text" rows="1" spellcheck="true" placeholder="${i === 0 ? "Start typing — @ adds a SmartLink" : "Type here…"}">${esc(node.text)}</textarea></div>`;
    }
    if (node.kind === "custom-smartlist") {
      const listName = normalizeName(node.listName);
      const head = `<div class="plan-head"><span class="plan-title">${icon("list", 17)}SmartList plan</span>${flagHtml(node)}</div>`;
      if (node.collapsed) {
        const c = choiceLines(node).length;
        return `${head}<button type="button" class="summary-btn" data-act="expand" aria-label="Expand SmartList plan"><span class="sum-text" style="font:500 15px var(--mono)">${esc(listName || "UNNAMED_LIST")}</span><span class="sum-meta">${esc(node.multiple)} · ${plural(c, "choice")} · Expand</span></button>`;
      }
      const opts = [["Single selection", "Single"], ["Multiple selections", "Multiple"], ["Confirm in Epic", "Decide in Epic"]];
      return `<div class="plan">${head}<p class="plan-note">Instructions for building a list in Epic — not a working SmartList. A placeholder copies in its place.</p>
        <div class="plan-grid">
          <div class="fld"><label for="${id}-ln">List name</label><input class="input mono" id="${id}-ln" data-field="listName" value="${esc(node.listName)}" placeholder="FOLLOWUP_OPTIONS" autocomplete="off" spellcheck="false"></div>
          <div class="fld"><span class="lbl" id="${id}-msl">Selection</span><div class="segmented" role="radiogroup" aria-labelledby="${id}-msl">${opts.map(([v, l], k) => `<input type="radio" id="${id}-m${k}" name="${id}-m" value="${esc(v)}" data-field="multiple" ${node.multiple === v ? "checked" : ""}><label for="${id}-m${k}">${l}</label>`).join("")}</div></div>
          <div class="fld wide"><label for="${id}-ch">Choices <small>one per line</small></label><textarea class="area" id="${id}-ch" data-field="choices" rows="3" placeholder="Improved&#10;No change&#10;Worse">${esc(node.choices)}</textarea></div>
          <div class="fld"><label for="${id}-df">Default choice</label><select class="select" id="${id}-df" data-field="defaultChoice"></select></div>
        </div></div>`;
    }
    const tok = node.token || "";
    if (node.kind === "wildcard") return `<div class="token-row"><code class="tok tok-wild">***</code><span class="tok-label">Wildcard</span>${flagHtml(node)}</div>`;
    return `<div class="token-row"><code class="tok ${tokenClass(tok)}">${esc(tok)}</code><span class="tok-label">${esc(shortLabel(node))}</span>${flagHtml(node)}</div>`;
  }
  function blockInner(node, i, count) {
    const n = i + 1;
    const collapsibleBtn = isCollapsible(node) ? `<button type="button" class="tool" data-act="collapse" tabindex="-1" aria-label="${node.collapsed ? "Expand" : "Collapse"} block ${n}" aria-expanded="${node.collapsed ? "false" : "true"}" title="${node.collapsed ? "Expand" : "Collapse to a summary"}" ${node.kind === "free-text" && !node.collapsed && !textIsLong(node.text) ? "hidden" : ""}>${icon(node.collapsed ? "expand" : "collapse")}</button>` : "";
    return `<button type="button" class="insert-here" data-act="insert-before" tabindex="-1" aria-label="Insert a block before block ${n}" title="Insert here"></button>
      <div class="gutter"><span class="handle" draggable="true" aria-hidden="true" title="Drag to move">${n}</span></div>
      <div class="bbody">${blockContent(node, i)}<ul class="block-problems" aria-live="polite"></ul></div>
      <div class="tools" role="toolbar" aria-label="Block ${n} actions">
        <button type="button" class="tool" data-act="add" tabindex="0" aria-label="Add a block below block ${n}" title="Add below">${icon("plus")}</button>
        ${(node.kind === "free-text" || node.kind === "template") && !node.collapsed ? `<button type="button" class="tool" data-act="inline" tabindex="-1" aria-label="Insert a SmartLink or wildcard at the cursor in block ${n}" title="Insert at cursor (type @)"><span class="at" aria-hidden="true">@</span></button>` : ""}
        ${canJoin(i) ? `<button type="button" class="tool" data-act="join" tabindex="-1" aria-label="Join block ${n} onto the end of block ${i}" title="Join onto the line above">${icon("join")}</button>` : ""}
        <span class="tool-sep" aria-hidden="true"></span>
        <button type="button" class="tool" data-act="up" tabindex="-1" aria-label="Move block ${n} up" title="Move up (Alt+↑)" ${i === 0 ? "disabled" : ""}>${icon("up")}</button>
        <button type="button" class="tool" data-act="down" tabindex="-1" aria-label="Move block ${n} down" title="Move down (Alt+↓)" ${i === count - 1 ? "disabled" : ""}>${icon("down")}</button>
        <button type="button" class="tool" data-act="duplicate" tabindex="-1" aria-label="Duplicate block ${n}" title="Duplicate">${icon("dup")}</button>
        ${collapsibleBtn}
        <button type="button" class="tool danger" data-act="remove" tabindex="-1" aria-label="Remove block ${n}" title="Remove">${icon("trash")}</button>
      </div>`;
  }
  function syncDefaultOptions(el, node) {
    const sel = el.querySelector('[data-field="defaultChoice"]');
    if (!sel) return;
    const choices = choiceLines(node);
    const cur = node.defaultChoice.trim();
    const opts = [["", "No default"], ...choices.map((c) => [c, c])];
    if (cur && !choices.includes(cur)) opts.push([cur, `${cur} (not a choice)`]);
    const html = opts.map(([v, l]) => `<option value="${esc(v)}"${v === cur ? " selected" : ""}>${esc(l)}</option>`).join("");
    if (sel._html !== html) { sel.innerHTML = html; sel._html = html; }
    sel.value = cur;
  }
  const INK_RE = new RegExp(`${TOKEN_RE_SRC}|\n`, "g");
  function inkClass(tok) { const c = tokenClass(tok); return c === "tok-wild" ? "ib-wild" : c === "tok-plan" ? "ib-plan" : "ib-link"; }
  function inkHtml(text) {
    let out = "", last = 0, m;
    INK_RE.lastIndex = 0;
    while ((m = INK_RE.exec(text))) {
      out += esc(text.slice(last, m.index));
      if (m[0] === "\n") out += `<span class="ib-br${m.index === 0 || text[m.index - 1] === "\n" ? " ib-para" : ""}"></span>\n`;
      else out += `<span class="ib ${inkClass(m[0])}">${esc(m[0])}</span>`;
      last = m.index + m[0].length;
    }
    return out + esc(text.slice(last));
  }
  function renderInk(ta) { const back = ta && ta.previousElementSibling; if (back && back.classList.contains("ink-back")) back.innerHTML = inkHtml(ta.value); }
  function caretRect(ta, pos) {
    const back = ta.previousElementSibling;
    const v = ta.value;
    back.innerHTML = `${esc(v.slice(0, pos))}<span class="ink-probe">\u200b</span>${esc(v.slice(pos))}`;
    const r = back.querySelector(".ink-probe").getBoundingClientRect();
    renderInk(ta);
    return r;
  }
  function tokenAround(text, pos, side) {
    let m;
    const re = new RegExp(TOKEN_RE_SRC, "g");
    while ((m = re.exec(text))) {
      const a = m.index, b = a + m[0].length;
      if (side === "before" ? b === pos : a === pos) return {start: a, end: b, text: m[0]};
      if (a > pos) break;
    }
    return null;
  }
  function autogrow(ta) { if (!ta || ta.tagName !== "TEXTAREA") return; ta.style.height = "auto"; ta.style.height = `${ta.scrollHeight + (ta.classList.contains("area") ? 2 : 0)}px`; }
  function syncFields(el, node) {
    el.querySelectorAll("[data-field]").forEach((f) => {
      const key = f.dataset.field;
      if (f.type === "radio") { f.checked = f.value === node.multiple; return; }
      if (key === "defaultChoice") return;
      const v = node[key] == null ? "" : String(node[key]);
      if (f.value !== v) f.value = v;
      autogrow(f);
      if (f.classList.contains("doc-text")) renderInk(f);
    });
    syncDefaultOptions(el, node);
  }

  function captureFocus() {
    const a = document.activeElement;
    if (!a || !blocksEl.contains(a)) return null;
    const b = a.closest(".block");
    if (!b) return null;
    return {uid: b.dataset.uid, field: a.dataset.field || null, act: a.dataset.act || null, value: a.type === "radio" ? a.value : null, isBlock: a === b, start: a.selectionStart, end: a.selectionEnd};
  }
  function restoreFocus(info) {
    if (!info) return;
    const el = blockEls.get(info.uid);
    if (!el) return;
    let target = el;
    if (info.field) target = el.querySelector(info.value != null ? `[data-field="${info.field}"][value="${CSS.escape(info.value)}"]` : `[data-field="${info.field}"]`) || el;
    else if (info.act) target = el.querySelector(`[data-act="${info.act}"]`) || el;
    if (target.disabled || target.hidden) target = el.querySelector('.tools .tool:not(:disabled):not([hidden])') || el;
    if (document.activeElement !== target) target.focus({preventScroll: true});
    if (info.field && typeof info.start === "number" && target.setSelectionRange) { try { target.setSelectionRange(info.start, info.end); } catch {} }
  }

  function renderBlocks(opts) {
    const animate = opts && opts.animate && !reducedMotion();
    const focusInfo = captureFocus();
    const before = animate ? new Map([...blockEls].map(([uid, el]) => [uid, el.getBoundingClientRect().top])) : null;
    const live = new Set(nodes.map((n) => n.uid));
    for (const [uid, el] of blockEls) if (!live.has(uid)) { el.remove(); blockEls.delete(uid); }
    nodes.forEach((node, i) => {
      let el = blockEls.get(node.uid);
      if (!el) {
        el = document.createElement("div");
        el.className = "block";
        el.dataset.uid = node.uid;
        el.tabIndex = -1;
        el.setAttribute("role", "group");
        blockEls.set(node.uid, el);
      }
      const sig = blockSig(node, i, nodes.length);
      if (el._sig !== sig) { el.innerHTML = blockInner(node, i, nodes.length); el._sig = sig; }
      el.dataset.kind = node.kind;
      el.setAttribute("aria-label", `Block ${i + 1}: ${kindLabel(node)}${node.kind === "free-text" ? "" : `, ${shortLabel(node)}`}`);
      el.classList.toggle("is-selected", node.uid === selectedUid);
      if (blocksEl.children[i] !== el) blocksEl.insertBefore(el, blocksEl.children[i] || null);
      syncFields(el, node);
    });
    $("#blocksEmpty").hidden = nodes.length > 0;
    restoreFocus(focusInfo);
    if (before) {
      blockEls.forEach((el, uid) => {
        if (!before.has(uid)) return;
        const dy = before.get(uid) - el.getBoundingClientRect().top;
        if (Math.abs(dy) < 1) return;
        el.style.transition = "none";
        el.style.transform = `translateY(${dy}px)`;
        requestAnimationFrame(() => { el.style.transition = "transform 160ms ease"; el.style.transform = ""; setTimeout(() => { el.style.transition = ""; }, 200); });
      });
    }
  }
